"""
Compute the ladder rungs (model sizes + FLOPs budgets) once, for the baseline architecture.
Writes ladder_config.json, which is then frozen. No GPU needed (uses train.py dry runs).

Rule: the mini rung is the original autoresearch baseline (depth 8, ~500M tokens ~ 300s on H100).
For every other rung we pick the (depth, width) whose size is closest to N_mini * sqrt(target_factor),
with width a multiple of 128 and an aspect ratio width/depth in [48, 80] (baseline: 64).
The compute budget is then C_k = C_mini * (N_k / N_mini)^2, which keeps the tokens/parameter ratio
exactly equal to the mini rung's along the whole ladder.

Usage: uv run sizes.py
"""

import json
import math
import os
import subprocess
import sys

MINI_DEPTH = 8
MINI_TOKENS = 500e6
RUNGS = {"nano": 0.2, "micro": 0.4, "mini": 1.0, "big": 10.0}  # compute factors vs mini
DEPTHS = range(3, 17)
WIDTHS = range(256, 1153, 128)
ASPECT_MIN, ASPECT_MAX = 48, 80
H100_PEAK = 989.5e12
ASSUMED_MFU = 0.35
# Memory heuristic from the baseline: ~44 GB at depth 8, width 512, micro-batch 128.
BASE_VRAM_GB, VRAM_LIMIT_GB = 44.0, 60.0
HERE = os.path.dirname(os.path.abspath(__file__))


def dry_run(depth, width):
    env = dict(os.environ, LADDER_DRY_RUN="1", LADDER_DEPTH=str(depth), LADDER_WIDTH=str(width))
    out = subprocess.run([sys.executable, os.path.join(HERE, "train.py")], env=env, cwd=HERE,
                         capture_output=True, text=True, check=True).stdout
    line = next(l for l in out.splitlines() if l.startswith("LADDER_DRY_RUN "))
    return json.loads(line[len("LADDER_DRY_RUN "):])


def pick_device_batch(depth, n_embd):
    for b in (128, 64, 32, 16, 8):
        est = BASE_VRAM_GB * (depth * n_embd) / (MINI_DEPTH * 512) * b / 128
        if est <= VRAM_LIMIT_GB:
            return b
    return 4


def main():
    shapes = [(d, w) for d in DEPTHS for w in WIDTHS if ASPECT_MIN <= w / d <= ASPECT_MAX]
    models = {s: dry_run(*s) for s in shapes}
    mini = models[(MINI_DEPTH, 512)]
    c_mini = mini["flops_per_token"] * MINI_TOKENS
    rungs = []
    for name, target in RUNGS.items():
        target_n = mini["n_non_emb"] * math.sqrt(target)
        shape = (MINI_DEPTH, 512) if name == "mini" else min(
            models, key=lambda s: (abs(math.log(models[s]["n_non_emb"] / target_n)),
                                   abs(s[1] / s[0] - 64)))
        m = models[shape]
        factor = (m["n_non_emb"] / mini["n_non_emb"]) ** 2
        flops = factor * c_mini
        tokens = flops / m["flops_per_token"]
        rungs.append(dict(
            name=name, depth=shape[0], width=m["n_embd"], target_factor=target, factor=factor, flops=flops,
            device_batch_size=pick_device_batch(shape[0], m["n_embd"]),
            n_non_emb=m["n_non_emb"], tokens=tokens, tokens_per_param=tokens / m["n_non_emb"],
            est_train_seconds=flops / (H100_PEAK * ASSUMED_MFU),
        ))
    big = next(r for r in rungs if r["name"] == "big")
    cfg = dict(target_flops=big["flops"], rungs=rungs,
               note="Generated by sizes.py for the baseline architecture. Frozen afterwards.")
    with open(os.path.join(HERE, "ladder_config.json"), "w") as f:
        json.dump(cfg, f, indent=2)
    print(f"{'rung':6s} {'depth':>5s} {'width':>5s} {'factor':>6s} {'N_non_emb':>10s} {'FLOPs':>10s} "
          f"{'tokens':>8s} {'tok/N':>6s} {'batch':>5s} {'~sec':>6s}")
    for r in rungs:
        print(f"{r['name']:6s} {r['depth']:5d} {r['width']:5d} {r['factor']:6.2f} {r['n_non_emb']/1e6:9.1f}M "
              f"{r['flops']:10.2e} {r['tokens']/1e6:7.0f}M {r['tokens_per_param']:6.1f} "
              f"{r['device_batch_size']:5d} {r['est_train_seconds']:6.0f}")


if __name__ == "__main__":
    main()
